#include <iostream>
using namespace std;

// Возводит a в степень n.
// Степень раскладываем на сумму 1, 2, 4, 8, 16 ...: например, 12 = 8 + 4,
// значит a^12 = a^8 * a^4.
// Цикл по очереди получает куски a, a^2, a^4, a^8 ... (каждый — квадрат прошлого)
// и умножает ответ на те куски, которые входят в сумму.
// Входит ли кусок, видно по остатку k % 2, после этого k делится пополам.
// Раз k каждый раз делится пополам, шагов около log2(n).
long long power(long long a, long long n) {
    long long res = 1;  // сюда собираем ответ
    for (long long k = n; k > 0; k = k / 2) {
        if (k % 2 == 1) {
            res = res * a;  // этот кусок входит в ответ
        }
        if (k > 1) {
            a = a * a;      // следующий кусок; после последнего шага он не нужен
        }
    }
    return res;
}

int main() {
    long long a, n;
    cout << "a = ";
    cin >> a;
    cout << "n = ";
    cin >> n;

    cout << a << "^" << n << " = " << power(a, n) << endl;
    return 0;
}
