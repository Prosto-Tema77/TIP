#include <iostream>
using namespace std;

// Находит НОД — наибольшее число, на которое делятся и a, и b.
// Алгоритм Евклида: НОД(a, b) = НОД(b, остаток от a / b).
// Так числа с каждым вызовом уменьшаются, пока остаток не станет 0.
// Пример: (9, 12) -> (12, 9) -> (9, 3) -> (3, 0) -> ответ 3
int gcd(int a, int b) {
    // b = 0 — ответ найден, это a. здесь вызовы заканчиваются
    if (b == 0) {
        return a;
    }
    // иначе ищем НОД для пары поменьше
    return gcd(b, a % b);
}

int main() {
    int a, b;
    cin >> a >> b;

    cout << gcd(a, b) << endl;
    return 0;
}
